#!/usr/bin/env node
/**
 * Bundles Ember_Legal_Pack.md (repo root) into src/legal/pack.generated.ts so
 * the app ships the legal text with no file loading at runtime, on native and
 * web alike. Runs before `npm run web`, `web:build`, `start`, `ios`, `android`.
 *
 * Until the pack is added, a clearly marked PLACEHOLDER is generated instead:
 * the screens render a "draft" banner and `npm run check:legal` fails, so it
 * can't slip into a submission unnoticed.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const src = path.join(root, 'Ember_Legal_Pack.md');
const out = path.join(root, 'src', 'legal', 'pack.generated.ts');
const check = process.argv.includes('--check');

const PLACEHOLDER = `# Privacy Policy

The Privacy Policy from Ember_Legal_Pack.md has not been added to this build yet.

# Medical Disclaimer

The Medical Disclaimer from Ember_Legal_Pack.md has not been added to this build yet.

# Terms of Service

The Terms of Service from Ember_Legal_Pack.md have not been added to this build yet.
`;

const present = fs.existsSync(src);
if (check) {
  if (!present) {
    console.error('[legal] Ember_Legal_Pack.md is missing — the app is showing placeholder legal text.');
    process.exit(1);
  }
  console.log('[legal] Ember_Legal_Pack.md present.');
  process.exit(0);
}

const markdown = present ? fs.readFileSync(src, 'utf8') : PLACEHOLDER;
const body =
  '// GENERATED by scripts/build-legal.js from Ember_Legal_Pack.md — do not edit.\n' +
  `export const LEGAL_IS_PLACEHOLDER = ${!present};\n` +
  `export const LEGAL_MARKDOWN = ${JSON.stringify(markdown)};\n`;

if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== body) fs.writeFileSync(out, body);
if (!present) console.warn('[legal] Ember_Legal_Pack.md not found — using placeholder legal text.');
